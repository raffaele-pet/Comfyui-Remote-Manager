_PAIRS = tuple(sorted(ENGLISH.items(), key=lambda item: len(item[0]), reverse=True))
_active_language = "en"
_dialogs_wrapped = False


@lru_cache(maxsize=4096)
def translate(text, language="en"):
    value = str(text)
    if language == "it":
        return value
    for italian, english in _PAIRS:
        if italian.isalpha():
            value = re.sub(rf"(?<!\w){re.escape(italian)}(?!\w)", lambda _match: english, value)
        else:
            value = value.replace(italian, english)
    return value


def set_active_language(language):
    global _active_language
    _active_language = language if language in ("en", "it") else "en"


def wrap_dialogs():
    """Translate dialog captions and prompts without changing call sites."""
    global _dialogs_wrapped
    if _dialogs_wrapped:
        return
    _dialogs_wrapped = True
    for module, names in (
        (messagebox, ("showinfo", "showwarning", "showerror", "askyesno", "askokcancel", "askyesnocancel")),
        (filedialog, ("askopenfilename", "asksaveasfilename", "askdirectory", "askopenfilenames")),
        (simpledialog, ("askstring", "askinteger", "askfloat")),
    ):
        for name in names:
            original = getattr(module, name)

            def localized(*args, _original=original, **kwargs):
                args = tuple(translate(arg, _active_language) if isinstance(arg, str) else arg for arg in args)
                for key in ("title", "message", "prompt"):
                    if isinstance(kwargs.get(key), str):
                        kwargs[key] = translate(kwargs[key], _active_language)
                return _original(*args, **kwargs)

            setattr(module, name, localized)
